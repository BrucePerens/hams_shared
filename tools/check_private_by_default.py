"""
Private-by-default ratchet for RPC-callable model methods.

Odoo refuses an RPC call to a method whose name starts with `_` or that is `@api.private`; every other public method of
a model is callable by any signed-in user over `/web/dataset/call_kw`. The `hams_rpc_guard` addon turns that into a
whitelist: each addon lists the public methods of its models in `rpc_exposure.json` (`internal`), generated by
`hams_rpc_guard/exposure_scan.py`, or marks one with `@public_rpc`. A new public method that is on neither fails
`hams_rpc_guard`'s own test. This check is the second half: the listed methods are debt (each is RPC-reachable only
because it was public when the list was made), and the debt may shrink but not grow.

For every `rpc_exposure.json` under the repository root it counts the methods listed under `internal` and compares the
count per module with a checked-in baseline (`private_by_default_baseline_<repo>.json`). It fails when

* a module has more listed methods than its baseline entry (a method was listed instead of being made private), or
* a module with listed methods has no baseline entry (a new module must start at zero: make its methods private, or
  declare the few that are meant to be callable with `@public_rpc`).

It prints the per-module counts every run. A module below its baseline passes with a note to lower the entry; the
baseline can only be lowered (`--write-baseline` refuses to raise a count). Each entry names an owner and the to-do that
tracks the renames (to leading-underscore names, in batches, during a quiet merge queue: no mass rename now).
"""

import argparse
import json
import os
import sys

EXPOSURE_FILE = "rpc_exposure.json"
SKIP_DIRS = {".git", "node_modules", "__pycache__", "tmp", "archive"}
DEFAULT_OWNER = "Bruce Perens (batch renames, quiet merge queue)"
DEFAULT_TRACKING = "night_shift_todo/medium/rpc-methods-private-by-default-renames-8c4e2f61.md"


def count_listed_methods(repo_root):
    """`{module: number of methods listed under "internal"}` for every addon directory that has an `rpc_exposure.json`."""
    counts = {}
    for entry in sorted(os.listdir(repo_root)):
        path = os.path.join(repo_root, entry, EXPOSURE_FILE)
        if entry in SKIP_DIRS or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as handle:
            document = json.load(handle)
        internal = document.get("internal") or {}
        counts[entry] = sum(len(methods) for methods in internal.values() if isinstance(methods, list))
    return counts


def load_baseline(path):
    """`{module: {"count": n, "owner": ..., "tracking": ...}}` from the baseline file; empty when the file is absent."""
    if not path or not os.path.isfile(path):
        return {}
    with open(path, encoding="utf-8") as handle:
        return json.load(handle).get("entries", {})


def compare(counts, baseline):
    """`(problems, notes)`: growth and unbaselined modules fail, a count below its baseline is a note."""
    problems, notes = [], []
    for module, count in sorted(counts.items()):
        entry = baseline.get(module)
        if entry is None:
            if count:
                problems.append(
                    "%s lists %d RPC-callable method(s) and has no baseline entry: make them private "
                    "(leading underscore or @api.private) or declare the few that must be public with @public_rpc" % (module, count))
        elif count > entry["count"]:
            problems.append("%s lists %d RPC-callable methods, baseline %d: a method was listed instead of made private" % (module, count, entry["count"]))
        elif count < entry["count"]:
            notes.append("%s is down to %d (baseline %d): lower its baseline entry" % (module, count, entry["count"]))
    for module in sorted(set(baseline) - set(counts)):
        notes.append("%s has a baseline entry but no %s: remove the entry" % (module, EXPOSURE_FILE))
    return problems, notes


def render_baseline(counts, previous):
    """The baseline text for `counts`; refuses (ValueError) to raise any count above `previous`."""
    entries = {}
    for module, count in sorted(counts.items()):
        if not count:
            continue
        old = previous.get(module)
        if old is not None and count > old["count"]:
            raise ValueError("refusing to raise the baseline of %s from %d to %d" % (module, old["count"], count))
        entries[module] = {
            "count": count,
            "owner": old["owner"] if old else DEFAULT_OWNER,
            "tracking": old["tracking"] if old else DEFAULT_TRACKING,
        }
    return json.dumps({"version": 1, "entries": entries}, indent=2) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("repo_root")
    parser.add_argument("--baseline")
    parser.add_argument("--write-baseline", action="store_true", help="write the baseline from the current counts (it can only go down)")
    args = parser.parse_args(argv)
    counts = count_listed_methods(args.repo_root)
    baseline = load_baseline(args.baseline)
    if args.write_baseline:
        text = render_baseline(counts, baseline)
        with open(args.baseline, "w", encoding="utf-8") as handle:
            handle.write(text)
        sys.stdout.write("wrote %s\n" % args.baseline)
        return 0
    total = sum(counts.values())
    sys.stdout.write("RPC-callable methods still public by default (listed in rpc_exposure.json): %d in %d module(s)\n" % (total, len([c for c in counts.values() if c])))
    for module, count in sorted(counts.items(), key=lambda item: -item[1]):
        if count:
            sys.stdout.write("  %-28s %4d\n" % (module, count))
    problems, notes = compare(counts, baseline)
    for note in notes:
        sys.stdout.write("[*] %s\n" % note)
    for problem in problems:
        sys.stdout.write("[!] CI/CD FAILURE: %s\n" % problem)
    if problems:
        return 1
    sys.stdout.write("[+] SUCCESS: no module's count of public-by-default RPC methods grew.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
