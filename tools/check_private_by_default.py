"""
Private-by-default check for RPC-callable model methods.

Odoo refuses an RPC call to a method whose name starts with `_` or that is `@api.private`; every other public method of
a model is callable by any signed-in user over `/web/dataset/call_kw`. The `hams_rpc_guard` addon turns that into a
whitelist: a public method must be `@api.private`, or declared with `@public_rpc` (a view button, JS, a daemon, a core
override), and `rpc_exposure.json` (`internal`, generated by `hams_rpc_guard/exposure_scan.py`) lists only what is
neither. The list reached zero on 2026-11-12 and the per-module baselines were deleted, so this check fails when any
`rpc_exposure.json` under the repository root lists a method under `internal`.
"""
import argparse
import json
import os
import sys

EXPOSURE_FILE = "rpc_exposure.json"
SKIP_DIRS = {".git", "node_modules", "__pycache__", "tmp", "archive"}


def count_listed_methods(repo_root):
    """`{module: number of methods listed under "internal"}` for every addon directory that has an `rpc_exposure.json`."""
    counts = {}
    for entry in sorted(os.listdir(repo_root)):
        path = os.path.join(repo_root, entry, EXPOSURE_FILE)
        if entry in SKIP_DIRS or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as handle:
            document = json.load(handle)
        internal = document.get("internal") or {}
        counts[entry] = sum(len(methods) for methods in internal.values() if isinstance(methods, list))
    return counts


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("repo_root")
    args = parser.parse_args(argv)
    counts = {module: count for module, count in count_listed_methods(args.repo_root).items() if count}
    for module, count in sorted(counts.items(), key=lambda item: -item[1]):
        sys.stdout.write("[!] CI/CD FAILURE: %s lists %d public-by-default RPC method(s): make them private (leading underscore or "
                         "@api.private) or declare them with @public_rpc, then regenerate with hams_rpc_guard/exposure_scan.py\n" % (module, count))
    if counts:
        return 1
    sys.stdout.write("[+] SUCCESS: no rpc_exposure.json lists a public-by-default RPC method.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
